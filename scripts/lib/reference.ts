export function coordinatesMd(level = '##'): string {
  return [
    `${level} Coordinates`,
    '',
    '- 1 stud = 1 unit along x and z. Heights count **plates**: `y` is the plate level of the brick\'s bottom (0 = on the baseplate). A plate or tile is 1 plate tall, a brick 3, so bricks stack at y = 0, 3, 6, 9...',
    '- Real proportions: a brick is 1 stud wide and 1.2 studs tall; a plate is 1/3 of a brick.',
    '- `x`, `z` = the **min corner**: the smallest x and z the part covers (integers >= 0).',
    '- Footprint: a part is `w x d` at r=0 (w along x, d along z). `r` = quarter turns counter-clockwise seen from above (0..3); r=1 or 3 swaps it to `d x w`. The part covers x..x+fx-1, z..z+fz-1, y..y+h-1.',
    '- Facing: parts with a front (slopes, windows, doors, figures, chairs...) face **+z at r=0**, +x at r=1, -z at r=2, -x at r=3. A slope\'s low edge is its front.',
    '- Photo mapping: **front = +z** (the side facing the camera), **x grows to the right**, y up; z=0 is the back row. The game\'s camera looks from the front-right.',
    `- Baseplate \`{w, d, c}\`: studs, 1..${PLATE_MAX}; use multiples of 8 (8, 16, 24, 32, 40, 48), leaving a stud or two of margin. \`c\` = colour id (defaults: building 5 green, vehicle 8 dark grey, prop 10 tan).`,
    `- City: a cell is ${CELL} studs. Placements give the min-corner cell \`cx, cz\`, \`rot\` 0..3 and size \`s\` 1..${MAX_SCALE}; a model covers ceil(w*s/${CELL}) x ceil(d*s/${CELL}) cells (swapped for odd rot). Roads, rails and terrain are lists of \`"cx,cz"\` keys.`,
    '',
  ].join('\n')
}

export function rulesMd(level = '##'): string {
  return [
    `${level} Build rules (checked; the import refuses a model that breaks them)`,
    '',
    '- Every part id and colour id must exist (see the tables).',
    '- Inside the baseplate: 0 <= x and x + fx <= w, 0 <= z and z + fz <= d.',
    `- Height: y >= 0 and y + h <= ${MAX_HEIGHT_PLATES} plates.`,
    '- **No overlaps**: no two parts share a stud cell at the same plate level.',
    '- **Support**: each part sits on the baseplate (y = 0) or has at least one footprint cell directly on top of another part (that part ends exactly at plate y). Nothing floats; nothing hangs under another part.',
    `- At most ${MAX_BRICKS} parts per model; a city has at most ${SHARE_LIMITS.cityBlueprints} blueprints, size <= ${SHARE_LIMITS.citySize}; names <= ${SHARE_LIMITS.nameLength} characters.`,
    `- Build steps (\`withSteps\`): built automatically layer by layer, <= ${MAX_STEP_SIZE} parts per step; each part must fit using only parts of earlier steps.`,
    '- City: a placement must stay inside the city and not cover a road, a rail, another placement or water (models tagged `water` instead need some water under them). No water under roads or rails; a road and a rail may share a cell only as a level crossing of two perpendicular straights.',
    '',
  ].join('\n')
}

export function approximationMd(level = '##'): string {
  return [
    `${level} Approximation rules`,
    '',
    '- Keep the **silhouette, proportions and colour blocks**; drop fine detail. Count studs on visible tops to get sizes.',
    '- Use the **biggest bricks that fit** (2x4, 2x6, 1x6, plates 4x8): fewer parts, sturdier, easier to build.',
    '- Make walls 1 stud thick and keep interiors **hollow**; stagger joints between courses when you can.',
    '- Map special pieces to the closest catalog part (an arch -> bricks + a window or door; a curved slope -> slope; a round brick -> round_1x1/2x2; a transparent piece -> a trans colour).',
    '- Windows: window_1x2x2 (2 bricks tall) or window_1x4x3 (3 bricks tall); doors are 6 bricks tall.',
    '- Roofs: slopes facing outwards (front row r=0, back row r=2, sides r=1 / r=3), a brick or plate ridge between them.',
    '- Vehicles (`blueprintKind` vehicle) drive toward **-z**: put the nose at the small-z end. Wheels stand on the plate (y=0) under the sides; the chassis plate rests on them (y=5 on wheel_small, y=8 on wheel_large).',
    '- Put minifigures where people are. Build bottom-up and check each layer has support.',
    '',
  ].join('\n')
}

