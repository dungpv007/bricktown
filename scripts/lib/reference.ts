function compactParts(): string {
  const rows = PARTS.map((p) => {
    const note = [SHAPE_NOTE[p.shape], hintFor(p)].filter(Boolean).join('; ')
    return `${p.id}|${p.w}x${p.d}|${p.h}|${p.category}${note ? `|${note}` : ''}`
  })
  return ['id|w x d|h(plates)|category|notes', ...rows].join('\n')
}

function compactColors(): string {
  return ['id|name|hex|LEGO name', ...COLORS.map((c) => `${c.id}|${c.name.en}${c.trans ? ' (trans)' : c.metal ? ' (metal)' : ''}|${c.hex}|${LEGO_NAMES[c.id] ?? ''}`)].join('\n')
}

