/** "Use this for..." hints by part id prefix or shape. */
function hintFor(p: PartDef): string {
  if (p.id.startsWith('brick_')) return p.w === 1 || p.d === 1 ? 'walls (1 stud thick), pillars, details' : 'solid blocks, thick walls, bases'
  if (p.id.startsWith('plate_')) return p.w * p.d >= 16 ? 'floors, foundations, roofs, vehicle chassis' : 'thin layers (1/3 brick), floors, ledges, steps'
  if (p.id.startsWith('tile_')) return 'smooth floors, paths, finishing tops'
  const byShape: Partial<Record<PartDef['shape'], string>> = {
    slope: 'roofs, ramps, car bonnets / windscreens',
    slope_inv: 'overhangs, under roof edges, boat hulls',
    cylinder: 'columns, towers, wheels hubs, barrels',
    cone: 'tower tips, traffic cones, roof finials',
    nose_cone: 'rocket and plane noses, round tower roofs',
    dish: 'satellite dishes, round lamps, wheels covers',
    engine: 'rocket / jet engines, exhausts',
    fin: 'rocket fins, plane tails, shark fins',
    window: p.h >= 9 ? 'big windows, shop fronts (3 bricks tall)' : 'small windows (2 bricks tall)',
    door: 'doors (6 bricks tall: walls need 6 courses around it)',
    fence: 'fences, railings, balconies',
    bars: 'jail windows, cages, gates',
    wheel: p.h >= 8 ? 'big wheels: trucks, fire engines' : 'small wheels: cars, carts',
    table: 'tables, desks', chair: 'chairs, seats', counter: 'kitchens, shop counters', stove: 'kitchens',
    fridge: 'kitchens', sign: 'shop signs, road signs', lamp: 'street lights', steering: 'vehicle cockpits',
    computer: 'offices, police stations', bed: 'bedrooms', tree: 'trees', bush: 'bushes, hedges', flower: 'gardens',
    flag: 'flags on roofs and towers', antenna: 'antennas, poles, masts', tile_print: 'signs and details (see prints)',
    minifig: 'people',
  }
  return byShape[p.shape] ?? ''
}

export function partsMd(): string {
  const lines = [
    GENERATED_NOTE,
    '# Parts',
    '',
    `Every part id the game knows (${PARTS.length}). Footprint \`w x d\` is in studs at r=0: w along x, d along z.`,
    'Odd rotations (r=1, r=3) swap it to `d x w`. Height is in plates: a plate is 1, a brick 3.',
    'Ids name sizes their own way (`slope_2x4` is 4 wide along x and 2 deep): trust the w x d column, not the id.',
    '',
  ]
  for (const cat of PART_CATEGORIES) {
    const parts = PARTS.filter((p) => p.category === cat)
    if (parts.length === 0) continue
    lines.push(`## ${cat}`, '', '| id | w x d | height (plates) | studs | notes | use for |', '|---|---|---|---|---|---|')
    for (const p of parts) {
      const note = [SHAPE_NOTE[p.shape] ?? '', p.print ? `print: \`${p.print}\`` : '', p.tags?.length ? `tags: ${p.tags.join(', ')}` : ''].filter(Boolean).join('; ')
      lines.push(`| \`${p.id}\` | ${p.w} x ${p.d} | ${plates(p.h)} | ${p.studs ? 'yes' : 'no'} | ${note} | ${hintFor(p)} |`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

